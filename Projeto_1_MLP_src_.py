        "# ---------------------------------------------------------------------------\n",
        "def baseline_regressao(y_train: np.ndarray, y_test: np.ndarray) -> Dict[str, float]:\n",
        "    \"\"\"\n",
        "    Baseline para regressão: prevê a mediana do conjunto de treino.\n",
        "    (Mais robusto que a média por ser resistente a outliers.)\n",
        "    \"\"\"\n",
        "    mediana = np.median(y_train)\n",
        "    preds = np.full_like(y_test, fill_value=mediana)\n",
        "\n",
        "    mae  = np.mean(np.abs(y_test - preds))\n",
        "    mse  = np.mean((y_test - preds) ** 2)\n",
        "    rmse = np.sqrt(mse)\n",
        "    ss_res = np.sum((y_test - preds) ** 2)\n",
        "    ss_tot = np.sum((y_test - np.mean(y_train)) ** 2)\n",
        "    r2 = 1 - (ss_res / ss_tot) if ss_tot > 0 else 0.0\n",
        "\n",
        "    print(f\"\\n[Baseline Regressão] Prediz mediana do treino: {mediana:.4f}\")\n",
        "    print(f\"  MSE={mse:.6f}  RMSE={rmse:.6f}  MAE={mae:.6f}  R²={r2:.6f}\")\n",
        "    return {'mediana': mediana, 'MAE': mae, 'RMSE': rmse, 'R2': r2, 'MSE': mse}\n",
