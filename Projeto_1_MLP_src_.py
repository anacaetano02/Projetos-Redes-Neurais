        "\n",
        "    for epoca in range(1, n_epocas + 1):\n",
        "        t0 = time.time()\n",
        "\n",
        "        # ── Fase de Treino ────────────────────────────────────────────────\n",
        "        modelo.train()\n",
        "        soma_loss_treino = 0.0\n",
        "        soma_acc_treino = 0.0\n",
        "        soma_grad_norm = 0.0\n",
        "        n_batches = 0\n",
        "\n",
        "        for X_batch, y_batch in loader_treino:\n",
