        "\n",
        "\n",
        "# ---------------------------------------------------------------------------\n",
        "# Funções auxiliares de métricas inline\n",
        "# ---------------------------------------------------------------------------\n",
        "def _acuracia(logits: torch.Tensor, targets: torch.Tensor) -> float:\n",
        "    \"\"\"Acurácia para classificação binária a partir de logits.\"\"\"\n",
        "    preds = (torch.sigmoid(logits) >= 0.5).float()\n",
        "    return (preds == targets).float().mean().item()\n",
        "\n",
        "\n",
        "def _gradient_norm(modelo: nn.Module) -> float:\n",
        "    \"\"\"\n",
        "    Calcula a norma L2 dos gradientes de todos os parâmetros treináveis.\n",
        "    Usado para diagnosticar vanishing/exploding gradients.\n",
        "    \"\"\"\n",
        "    total_norm = 0.0\n",
        "    for p in modelo.parameters():\n",
        "        if p.grad is not None:\n",
        "            total_norm += p.grad.data.norm(2).item() ** 2\n",
        "    return total_norm ** 0.5\n",
        "\n",
        "\n",
        "# ---------------------------------------------------------------------------\n",
        "# Training loop: Classificação\n",
        "# ---------------------------------------------------------------------------\n",
        "def treinar_classificador(\n",
