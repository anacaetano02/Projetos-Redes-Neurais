        "    - Registro de gradient norms para diagnóstico\n",
        "    - Checkpointing via state_dict (salva melhor modelo)\n",
        "    - Early stopping por val_loss\n",
        "    - Logging no TensorBoard\n",
        "\n",
        "    Retorna\n",
        "    -------\n",
        "    historico : dict\n",
